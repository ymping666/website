export function translate(text, dictionary = zhUI) {
  if (typeof text !== 'string') return text;
  const value = text.trim();
  let result = dictionary[value];
  if (result === undefined) {
    const translated = part => translate(part, dictionary);
    const patterns = [
      [/^(\d+) min$/, (_, n) => `${n} 分钟`],
      [/^Original, verified coding exercises covering (.+)\.$/, (_, description) => `原创、独立验证的编程练习，覆盖${translated(description)}。`],
      [/^(.+) Download here before reloading or leaving this page\.$/, (_, error) => `${translated(error)} 请在当前页下载备份，再刷新或离开。`],
      [/^(\d+)\/(\d+) solved$/, (_, n, all) => `已完成 ${n}/${all} 题`],
      [/^of (\d+) problems solved$/, (_, n) => `共 ${n} 题中的已完成题数`],
      [/^(\d+) accepted problems?$/, (_, n) => `通过 ${n} 道题`],
      [/^(\d+)\/([\d]+) solved$/, (_, n, all) => `已完成 ${n}/${all}`],
      [/^(\d+)\/(\d+) day best streak$/, (_, n, all) => `最佳连续 ${n}/${all} 天`],
      [/^(\d+)\/(\d+) set completed$/, (_, n, all) => `已完成 ${n}/${all} 个题单`],
      [/^Show hint (\d+) \/ (\d+)$/, (_, n, all) => `查看提示 ${n} / ${all}`],
      [/^(✓ )?(\d+)\/(\d+) passed$/, (_, mark = '', n, all) => `${mark}${n}/${all} 通过`],
      [/^Running (\d+)\/(\d+) tests…$/, (_, n, all) => `正在运行测试 ${n}/${all}…`],
      [/^Running (full suite|samples)…$/, (_, mode) => mode === 'samples' ? '正在运行示例…' : '正在运行完整测试…'],
      [/^(Full local suite|Sample tests) · (\d+) of (\d+) passed · ([\d.]+)s$/, (_, mode, n, all, seconds) => `${mode === 'Sample tests' ? '示例测试' : '完整本地测试'} · ${n}/${all} 通过 · ${seconds} 秒`],
      [/^Continue: (.+) →$/, (_, title) => `继续：${translated(title)} →`],
      [/^Next: (.+) →$/, (_, title) => `下一题：${translated(title)} →`],
      [/^(.+) · Review$/, (_, title) => `${translated(title)} · 复习`],
      [/^(\d+)\/(\d+) solved · (\d+) day practice streak · (\d+) active days this week$/, (_, n, all, streak, active) => `已完成 ${n}/${all} 题 · 连续练习 ${streak} 天 · 最近七天练习 ${active} 天`],
      [/^(\d{4}-\d{2}-\d{2}): (\d+) test runs, (\d+) problems accepted$/, (_, date, runs, accepted) => `${date}：运行测试 ${runs} 次，通过 ${accepted} 题`],
      [/^Backup merged\. (\d+) solved records read; (\d+) existing drafts kept\. Your current goal is preserved on this browser\.$/, (_, read, kept) => `备份已合并，读取 ${read} 条完成记录，保留 ${kept} 份已有草稿。当前浏览器的已有目标不被覆盖。`],
      [/^Python runtime error: ([\s\S]+)\. Check your network and retry\.$/, (_, error) => `Python 运行错误：${error}。请检查网络后重试。`],
      [/^Unable to start Python: ([\s\S]+)$/, (_, error) => `无法启动 Python：${error}`],
      [/^(.+) — (Solution|coding challenge|explained solution|coding challenges|practice set)$/, (_, title, type) => `${translated(title)} — ${{Solution:'题解','coding challenge':'编程练习','explained solution':'详解','coding challenges':'编程练习','practice set':'专题题单'}[type]}`],
      [/^(.+) coding challenges$/, (_, title) => `${translated(title)}编程练习`],
      [/^(.+) Python solution with complexity, edge cases and annotated reasoning\.$/, (_, title) => `${translated(title)}：Python 参考实现、复杂度、边界情况与思路解析。`],
      [/^Related topic: (.+)$/, (_, title) => `相关主题：${translated(title)}`],
      [/^(.+) (solved|progress)$/, (_, title, type) => `${translated(title)}${type === 'solved' ? '完成题数' : '进度'}`],
      [/^Concept: (.+)$/, (_, title) => `知识点：${translated(title)}`],
      [/^(\d+)\. (.+)$/, (_, n, title) => `${n}. ${translated(title)}`],
      [/^Example (\d+) — (.+)$/, (_, n, title) => `示例 ${n} — ${translated(title)}`],
      [/^(\d+) (published exercises|verified exercises|exercises) →$/, (_, n) => `${n} 道已验证练习 →`],
      [/^(\d+) (published exercises|published, independently tested coding challenges|verified exercises in this topic)\.?$/, (_, n) => `${n} 道独立验证的已发布练习`],
      [/^Run samples: first 2 cases · Submit: all (\d+) inspectable local tests\.$/, (_, n) => `运行示例：前 2 个用例 · 提交：全部 ${n} 个可查看的本地测试。`],
      [/^FREE EDITORIAL · (.+)$/, (_, track) => `免费题解 · ${translated(track)}`],
      [/^All (\d+) published exercises have original contracts, editorial explanations and reference implementations checked against their stated tests\. Planned topics are not counted as published problems\.$/, (_, n) => `全部 ${n} 道已发布练习均有原创约定、题解与通过相应测试的参考实现。规划中的内容不计入题目数量。`],
      [/^(.+) \| TensorDrill$/, (_, title) => `${translated(title)} | TensorDrill`]
    ];
    for (const [pattern, render] of patterns) {
      if (pattern.test(value)) { result = value.replace(pattern, render); break; }
    }
    if (result === undefined && /[A-Z]/.test(value)) {
      const key = Object.keys(dictionary).find(key => key.toUpperCase() === value);
      if (key) result = dictionary[key];
    }
    if (result === undefined && /[.。]$/.test(value) && dictionary[value.slice(0,-1)] !== undefined) result = dictionary[value.slice(0,-1)] + '。';
    if (result === undefined) {
      for (const separator of [' · ', ' / ']) {
        if (!value.includes(separator)) continue;
        const parts = value.split(separator), localized = parts.map(translated);
        if (localized.some((part, i) => part !== parts[i])) { result = localized.join(separator); break; }
      }
    }
    if (result === undefined && / (→|↗)$/.test(value)) {
      const prefix = value.slice(0,-2), localized = translated(prefix);
      if (localized !== prefix) result = localized + value.slice(-2);
    }
  }
  return result === undefined ? text : text.replace(value, result);
}
